package com.idheima.literalandvariable;

public class VariableDemo4 {
    public static void main(String[] args){
        byte b = 1;
        short s = 32767;
        int i = 2000;
        long l = 1000000000000000L;//细节：long类型数据必须以L结尾，建议大写
        float f = 3.14F;//细节：float类型数据必须以F结尾，建议大写
        double d = 3.14D;//细节：double类型数据必须以D结尾，建议大写
        char c = 'a';
        boolean flag = true;//or false
    }
}
